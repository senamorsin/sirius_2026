def new_document(size=14):
    document = Document()
    section = document.sections[0]
    section.page_width, section.page_height = Cm(21), Cm(29.7)
    section.top_margin = section.bottom_margin = Cm(2)
    section.left_margin = section.right_margin = Cm(2)
    normal = document.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(size)
    for name in ("Normal", "Heading 1", "Heading 2"):
        fonts = document.styles[name].element.get_or_add_rPr().get_or_add_rFonts()
        for key in list(fonts.attrib):
            if key.endswith("Theme"):
                del fonts.attrib[key]
        for key in ("ascii", "hAnsi", "eastAsia", "cs"):
            fonts.set(qn("w:" + key), "Times New Roman")
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.space_after = Pt(0)
    normal.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    for name in ("Heading 1", "Heading 2"):
        style = document.styles[name]
        style.font.name = "Times New Roman"
        style.font.size = Pt(14)
        style.font.bold = True
        style.font.color.rgb = None
    return document


def numbering(document):
    section = document.sections[0]
    section.different_first_page_header_footer = True
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    field = OxmlElement("w:fldSimple")
    field.set(qn("w:instr"), "PAGE")
    footer._p.append(field)


def paragraph(document, text):
    return document.add_paragraph(text)


def page(document, title, texts):
    document.add_page_break()
    if title.startswith("Приложение "):
        number, title = title.split(". ", 1)
        p = paragraph(document, number)
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    document.add_heading(title, 1)
    for text in texts:
        paragraph(document, text)


def caption(document, text):
    p = paragraph(document, text)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER


def table(document, title, headers, rows, number):
    p = paragraph(document, f"Таблица {number}")
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    caption(document, title)
    result = document.add_table(rows=1, cols=len(headers), style="Table Grid")
    for cell, text in zip(result.rows[0].cells, headers, strict=True):
        cell.text = text
    for row in rows:
        for cell, text in zip(result.add_row().cells, row, strict=True):
            cell.text = str(text)
    for row in result.rows:
        for cell in row.cells:
            for p in cell.paragraphs:
                p.paragraph_format.line_spacing = 1.0
                for run in p.runs:
                    run.font.size = Pt(12)


