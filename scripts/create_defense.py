def text_box(slide, x, y, width, height, text, size=28, color="FFFFFF", bold=False):
    frame = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(width), Inches(height)).text_frame
    frame.word_wrap = True
    for i, line in enumerate(text.split("\n")):
        p = frame.paragraphs[0] if i == 0 else frame.add_paragraph()
        p.text = line
        p.font.name, p.font.size = "Arial", SlidePt(size)
        p.font.bold = bold
        p.font.color.rgb = RGBColor.from_string(color)
        p.line_spacing = 1.5
        p.space_after = SlidePt(14)
    return frame


